# ============================================================
# NLP EXTRACTOR
# ============================================================

class NLPExtractor:
    """
    NER Extractor:

        GLiNER
           ↓
        spaCy fallback
           ↓
        Regex always

    Relationship Extractor:

        Groq
           ↓
        co-occurrence fallback
    """

    def __init__(self):
        self._gliner_model = None
        self._spacy_nlp = None
        self._extraction_engine = "none"

        # ----------------------------------------------------
        # Regex patterns for deterministic Indian PII
        # ----------------------------------------------------

        self._phone_pattern = re.compile(
            r"(?:(?:\+91|0)?[\s\-]?)?"
            r"(?:\d{5}[\s\-]?\d{5}|\d{10})"
        )

        self._imei_pattern = re.compile(
            r"\b\d{15}\b"
        )

        self._vehicle_pattern = re.compile(
            r"\b[A-Z]{2}\s?\d{1,2}\s?[A-Z]{1,3}\s?\d{1,4}\b",
            re.IGNORECASE,
        )

        self._law_pattern = re.compile(
            r"(?:BNS|IPC|CrPC|BNSS|IT Act|NDPS|POCSO)"
            r"\s*(?:§|Section|Sec\.?)\s*\d+[A-Z]?",
            re.IGNORECASE,
        )

        self._pincode_pattern = re.compile(
            r"\b[1-9]\d{5}\b"
        )

        self._aadhaar_pattern = re.compile(
            r"\b[2-9]\d{3}\s?\d{4}\s?\d{4}\b"
        )

        self._ifsc_pattern = re.compile(
            r"\b[A-Z]{4}0[A-Z0-9]{6}\b"
        )

        self._pan_pattern = re.compile(
            r"\b[A-Z]{5}\d{4}[A-Z]\b"
        )

        self._upi_pattern = re.compile(
            r"\b[a-zA-Z0-9.\-_]{2,256}"
            r"@[a-zA-Z]{2,64}\b"
        )

        self._load_engines()

    # ========================================================
    # ENGINE LOADING
    # ========================================================

    def _load_engines(self):
        """
        Try GLiNER first.
        Fall back to spaCy if GLiNER fails.
        """

        # ----------------------------------------------------
        # GLiNER
        # ----------------------------------------------------

        if USE_GLINER:
            try:
                from gliner import GLiNER

                logger.info(
                    f"Loading GLiNER model: {GLINER_MODEL}"
                )

                self._gliner_model = GLiNER.from_pretrained(
                    GLINER_MODEL
                )

                self._extraction_engine = "gliner"

                logger.info(
                    "GLiNER loaded — using zero-shot crime-domain NER"
                )

                return

            except Exception as e:
                logger.warning(
                    f"GLiNER load failed: {e}. "
                    "Falling back to spaCy."
                )

        # ----------------------------------------------------
        # spaCy fallback
        # ----------------------------------------------------

        try:
            import spacy

            try:
                self._spacy_nlp = spacy.load(SPACY_MODEL)

            except OSError:
                logger.warning(
                    f"{SPACY_MODEL} not found. "
                    "Trying en_core_web_sm."
                )

                self._spacy_nlp = spacy.load(
                    "en_core_web_sm"
                )

            self._extraction_engine = "spacy"

            logger.info(
                f"spaCy loaded: {SPACY_MODEL}"
            )

        except Exception as e:
            logger.error(
                f"Both GLiNER and spaCy failed to load: {e}"
            )

            self._extraction_engine = "regex_only"

    # ========================================================
    # ENTITY EXTRACTION
    # ========================================================

    def extract_entities_with_spans(
        self,
        text: str,
    ) -> list[dict]:

        """
        Extract entities using:

            GLiNER OR spaCy
            +
            Regex

        Returns entities with source spans.
        """

        if not text or len(text.strip()) < 5:
            return []

        entities = []

        # ----------------------------------------------------
        # GLiNER
        # ----------------------------------------------------

        if (
            self._extraction_engine == "gliner"
            and self._gliner_model
        ):
            entities.extend(
                self._extract_with_gliner(text)
            )

        # ----------------------------------------------------
        # spaCy fallback
        # ----------------------------------------------------

        elif (
            self._extraction_engine == "spacy"
            and self._spacy_nlp
        ):
            entities.extend(
                self._extract_with_spacy(text)
            )

        # ----------------------------------------------------
        # Regex ALWAYS runs
        # ----------------------------------------------------

        entities.extend(
            self._extract_with_regex(text)
        )

        # ----------------------------------------------------
        # Deduplicate overlapping entities
        # ----------------------------------------------------

        entities = self._deduplicate_entities(
            entities
        )

        logger.info(
            f"NER: {len(entities)} entities via "
            f"{self._extraction_engine} "
            f"("
            f"{sum(1 for e in entities if e['label'] == 'PERSON')}"
            f" persons)"
        )

        return entities

    # ========================================================
    # GLiNER ENTITY EXTRACTION
    # ========================================================

    def _extract_with_gliner(
        self,
        text: str,
    ) -> list[dict]:

        """
        GLiNER entity extraction.

        Long text is split into sentence-aware chunks.
        Individual long sentences are hard-split so GLiNER
        does not receive excessively long sequences.
        """

        try:
            chunks = self._chunk_text(
                text,
                max_chars=900,
            )

            all_entities = []

            for chunk, offset in chunks:

                try:
                    raw = self._gliner_model.predict_entities(
                        chunk,
                        CRIME_ENTITY_LABELS,
                        threshold=GLINER_THRESHOLD,
                    )

                except Exception as e:
                    logger.warning(
                        f"GLiNER chunk failed: {e}"
                    )
                    continue

                for ent in raw:

                    gliner_label = (
                        ent.get("label", "")
                        .lower()
                        .strip()
                    )

                    db_label = GLINER_LABEL_TO_DB.get(
                        gliner_label,
                        "ORGANIZATION",
                    )

                    ent_start = ent.get(
                        "start",
                        0,
                    )

                    ent_end = ent.get(
                        "end",
                        0,
                    )

                    source_sentence = (
                        self._find_source_sentence(
                            chunk,
                            ent_start,
                            ent_end,
                        )
                    )

                    entity_text = (
                        ent.get("text", "")
                        .strip()
                    )

                    if not entity_text:
                        continue

                    all_entities.append(
                        {
                            "text": entity_text,
                            "label": db_label,
                            "gliner_label": gliner_label,
                            "start": offset + ent_start,
                            "end": offset + ent_end,
                            "confidence": round(
                                float(
                                    ent.get(
                                        "score",
                                        0.0,
                                    )
                                ),
                                3,
                            ),
                            "source_sentence": (
                                source_sentence[:200]
                            ),
                            "page": 1,
                            "engine": "gliner",
                        }
                    )

            return all_entities

        except Exception as e:
            logger.error(
                f"GLiNER extraction failed: {e}"
            )

            return []

    # ========================================================
    # SPACY ENTITY EXTRACTION
    # ========================================================

    def _extract_with_spacy(
        self,
        text: str,
    ) -> list[dict]:

        entities = []

        try:
            doc = self._spacy_nlp(text)

            spacy_map = {
                "PERSON": "PERSON",
                "ORG": "ORGANIZATION",
                "GPE": "LOCATION",
                "LOC": "LOCATION",
                "DATE": "DATE",
                "MONEY": "MONEY",
                "TIME": "DATE",
                "CARDINAL": "DATE",
                "LAW": "ORGANIZATION",
                "EVENT": "ORGANIZATION",
                "FAC": "LOCATION",
            }

            for ent in doc.ents:

                if ent.label_ not in spacy_map:
                    continue

                sentence = next(
                    (
                        sent.text.strip()
                        for sent in doc.sents
                        if (
                            sent.start_char
                            <= ent.start_char
                            and
                            sent.end_char
                            >= ent.end_char
                        )
                    ),
                    "",
                )

                entities.append(
                    {
                        "text": ent.text.strip(),
                        "label": spacy_map[ent.label_],
                        "gliner_label": (
                            ent.label_.lower()
                        ),
                        "start": ent.start_char,
                        "end": ent.end_char,
                        "confidence": 0.85,
                        "source_sentence": (
                            sentence[:200]
                        ),
                        "page": 1,
                        "engine": "spacy",
                    }
                )

        except Exception as e:
            logger.error(
                f"spaCy extraction failed: {e}"
            )

        return entities

    # ========================================================
    # REGEX EXTRACTION
    # ========================================================

    def _extract_with_regex(
        self,
        text: str,
    ) -> list[dict]:

        """
        Deterministic extraction for structured identifiers.
        """

        regex_entities = []

        patterns = [
            (
                "PHONE",
                self._phone_pattern,
                "phone number",
            ),
            (
                "PHONE",
                self._imei_pattern,
                "imei",
            ),
            (
                "VEHICLE",
                self._vehicle_pattern,
                "vehicle registration",
            ),
            (
                "ORGANIZATION",
                self._law_pattern,
                "law section",
            ),
            (
                "LOCATION",
                self._pincode_pattern,
                "pincode",
            ),
            (
                "PERSON",
                self._aadhaar_pattern,
                "aadhaar number",
            ),
            (
                "BANK_ACCOUNT",
                self._ifsc_pattern,
                "ifsc code",
            ),
            (
                "PERSON",
                self._pan_pattern,
                "pan card",
            ),
            (
                "BANK_ACCOUNT",
                self._upi_pattern,
                "upi id",
            ),
        ]

        for db_label, pattern, gliner_label in patterns:

            for match in pattern.finditer(text):

                matched_text = (
                    match.group().strip()
                )

                if len(matched_text) < 4:
                    continue

                source_sentence = (
                    self._find_source_sentence(
                        text,
                        match.start(),
                        match.end(),
                    )
                )

                regex_entities.append(
                    {
                        "text": matched_text,
                        "label": db_label,
                        "gliner_label": gliner_label,
                        "start": match.start(),
                        "end": match.end(),
                        "confidence": 1.0,
                        "source_sentence": (
                            source_sentence[:200]
                        ),
                        "page": 1,
                        "engine": "regex",
                    }
                )

        return regex_entities

    # ========================================================
    # GLiNER CHUNKING
    # ========================================================

    @staticmethod
    def _chunk_text(
        text: str,
        max_chars: int = 900,
    ) -> list[tuple[str, int]]:

        """
        Sentence-aware chunking for GLiNER.

        Why 900 characters?

        GLiNER internally has a token limit. Character count is
        not identical to token count, but keeping chunks around
        900 characters provides a safe practical margin.

        Strategy:

            paragraph/sentence
                    ↓
            accumulate sentences
                    ↓
            max_chars reached
                    ↓
            create chunk

        If one sentence itself is too long:

            long sentence
                    ↓
            whitespace-aware hard split
                    ↓
            small chunks
        """

        if not text or not text.strip():
            return []

        # ----------------------------------------------------
        # Sentence splitting
        #
        # Supports:
        #   .
        #   !
        #   ?
        #   ।
        #   newlines
        # ----------------------------------------------------

        sentences = re.split(
            r"(?<=[.!?।])\s+|\n+",
            text.strip(),
        )

        sentences = [
            sentence.strip()
            for sentence in sentences
            if sentence.strip()
        ]

        chunks: list[tuple[str, int]] = []

        current_parts: list[str] = []
        current_length = 0
        current_start = None

        # Track original location approximately by searching
        # sequentially through the original text.
        search_position = 0

        for sentence in sentences:

            sentence_start = text.find(
                sentence,
                search_position,
            )

            if sentence_start == -1:
                sentence_start = search_position

            sentence_end = (
                sentence_start + len(sentence)
            )

            search_position = sentence_end

            # ------------------------------------------------
            # Sentence fits into current chunk
            # ------------------------------------------------

            additional_length = (
                len(sentence)
                + (1 if current_parts else 0)
            )

            if (
                current_parts
                and
                current_length + additional_length
                <= max_chars
            ):
                current_parts.append(sentence)
                current_length += additional_length
                continue

            # ------------------------------------------------
            # Save existing chunk
            # ------------------------------------------------

            if current_parts:

                chunk_text = " ".join(
                    current_parts
                )

                chunks.append(
                    (
                        chunk_text,
                        current_start if current_start is not None else 0,
                    )
                )

                current_parts = []
                current_length = 0
                current_start = None

            # ------------------------------------------------
            # Sentence itself fits
            # ------------------------------------------------

            if len(sentence) <= max_chars:

                current_parts = [sentence]
                current_length = len(sentence)
                current_start = sentence_start

                continue

            # ------------------------------------------------
            # Individual sentence is too long
            #
            # Hard split on whitespace rather than cutting
            # through words.
            # ------------------------------------------------

            words = sentence.split()

            piece_words: list[str] = []
            piece_length = 0
            piece_start = sentence_start

            cursor = sentence_start

            for word in words:

                word_position = text.find(
                    word,
                    cursor,
                )

                if word_position == -1:
                    word_position = cursor

                cursor = (
                    word_position
                    + len(word)
                )

                additional = (
                    len(word)
                    + (1 if piece_words else 0)
                )

                if (
                    piece_words
                    and
                    piece_length + additional
                    > max_chars
                ):

                    piece = " ".join(
                        piece_words
                    )

                    chunks.append(
                        (
                            piece,
                            piece_start,
                        )
                    )

                    piece_words = []
                    piece_length = 0

                    # Start next piece approximately at
                    # the current word.
                    piece_start = word_position

                piece_words.append(word)

                piece_length += (
                    len(word)
                    + (1 if len(piece_words) > 1 else 0)
                )

            if piece_words:

                piece = " ".join(
                    piece_words
                )

                chunks.append(
                    (
                        piece,
                        piece_start,
                    )
                )

        # ----------------------------------------------------
        # Final accumulated chunk
        # ----------------------------------------------------

        if current_parts:

            chunk_text = " ".join(
                current_parts
            )

            chunks.append(
                (
                    chunk_text,
                    current_start if current_start is not None else 0,
                )
            )

        return chunks

    # ========================================================
    # SOURCE SENTENCE
    # ========================================================

    @staticmethod
    def _find_source_sentence(
        text: str,
        start: int,
        end: int,
    ) -> str:

        """
        Extract the sentence containing an entity.
        Supports English and Devanagari danda punctuation.
        """

        if not text:
            return ""

        start = max(
            0,
            min(start, len(text)),
        )

        end = max(
            start,
            min(end, len(text)),
        )

        # ----------------------------------------------------
        # First try proper sentence boundaries
        # ----------------------------------------------------

        left_boundary = max(
            text.rfind(".", 0, start),
            text.rfind("!", 0, start),
            text.rfind("?", 0, start),
            text.rfind("।", 0, start),
            text.rfind("\n", 0, start),
        )

        right_candidates = [
            position
            for position in [
                text.find(".", end),
                text.find("!", end),
                text.find("?", end),
                text.find("।", end),
                text.find("\n", end),
            ]
            if position != -1
        ]

        if right_candidates:
            right_boundary = min(
                right_candidates
            )
        else:
            right_boundary = len(text)

        sentence = text[
            left_boundary + 1:right_boundary + 1
        ].strip()

        if sentence:
            return sentence

        # ----------------------------------------------------
        # Fallback: local context
        # ----------------------------------------------------

        left = max(
            0,
            start - 150,
        )

        right = min(
            len(text),
            end + 150,
        )

        return text[left:right].strip()

    # ========================================================
    # ENTITY DEDUPLICATION
    # ========================================================

    @staticmethod
    def _deduplicate_entities(
        entities: list[dict],
    ) -> list[dict]:

        if not entities:
            return []

        # Sort by:
        #   1. start position
        #   2. confidence descending
        #   3. longer entity first
        entities.sort(
            key=lambda e: (
                e["start"],
                -e.get("confidence", 0),
                -(e["end"] - e["start"]),
            )
        )

        deduped = []

        for ent in entities:

            if not deduped:
                deduped.append(ent)
                continue

            previous = deduped[-1]

            # ------------------------------------------------
            # No overlap
            # ------------------------------------------------

            if ent["start"] >= previous["end"]:
                deduped.append(ent)
                continue

            # ------------------------------------------------
            # Overlap
            #
            # Keep the entity with higher confidence.
            # If confidence is equal, keep the longer span.
            # ------------------------------------------------

            current_confidence = ent.get(
                "confidence",
                0,
            )

            previous_confidence = previous.get(
                "confidence",
                0,
            )

            current_length = (
                ent["end"] - ent["start"]
            )

            previous_length = (
                previous["end"]
                - previous["start"]
            )

            if (
                current_confidence
                > previous_confidence
                or (
                    current_confidence
                    == previous_confidence
                    and current_length
                    > previous_length
                )
            ):
                deduped[-1] = ent

        return deduped

    # ========================================================
    # RELATIONSHIP EXTRACTION
    # ========================================================

    def extract_relationships(
        self,
        text: str,
        known_entities: Optional[list[str]] = None,
    ) -> list[dict]:

        """
        Relationship extraction:

            Groq
              ↓
            fallback
              ↓
        co-occurrence relations
        """

        if not text or len(text.strip()) < 50:
            return []

        try:

            relations = self._llm_layer(
                text,
                known_entities,
            )

            if relations:
                return relations

        except Exception as e:

            logger.warning(
                f"Groq relationship extraction failed: {e}"
            )

        # ----------------------------------------------------
        # Groq failed → deterministic fallback
        # ----------------------------------------------------

        return self._cooccurrence_relations(
            text
        )

    # ========================================================
    # GROQ RELATIONSHIP EXTRACTION
    # ========================================================

    def _llm_layer(
        self,
        text: str,
        known_entities: Optional[list[str]] = None,
    ) -> list[dict]:

        """
        Extract semantic relationships using Groq.

        Important design choice:

        Groq returns ONLY:
            source
            target
            relation

        Evidence is recovered from the original FIR text
        afterwards. This makes structured JSON generation
        much more reliable and reduces token usage.
        """

        if not GROQ_API_KEY:

            logger.warning(
                "No GROQ_API_KEY set. "
                "Skipping LLM relationship layer."
            )

            return []

        try:
            from groq import Groq

            client = Groq(
                api_key=GROQ_API_KEY
            )

            # ------------------------------------------------
            # Known entity hints
            # ------------------------------------------------

            entity_hint = ""

            if known_entities:

                cleaned_entities = [
                    str(entity).strip()
                    for entity in known_entities[:20]
                    if str(entity).strip()
                ]

                if cleaned_entities:

                    entity_hint = (
                        "\nKnown entities found by the "
                        "NER system:\n"
                        + "\n".join(
                            f"- {entity}"
                            for entity in cleaned_entities
                        )
                    )

            # ------------------------------------------------
            # Limit input size
            # ------------------------------------------------

            fir_text = text[:4000]

            # ------------------------------------------------
            # Strict JSON prompt
            # ------------------------------------------------

            prompt = f"""
Extract relationships between people/entities explicitly
mentioned in the following FIR.

Allowed relationship types ONLY:

- family
- associate
- same_organization
- phone_call
- financial_transfer

Rules:

1. Only create relationships directly supported by the FIR.
2. Do not invent entities.
3. Use the entity names exactly as they appear in the text
   whenever possible.
4. Do not create a relationship merely because two people
   are mentioned somewhere in the document.
5. Do not explain your reasoning.
6. Do not return markdown.
7. Do not return code fences.
8. Return ONLY a JSON object.
9. If no valid relationship exists, return:
   {{"relations": []}}

{entity_hint}

FIR TEXT:
{fir_text}

Return exactly this JSON structure:

{{
  "relations": [
    {{
      "source": "Person A",
      "target": "Person B",
      "relation": "associate"
    }}
  ]
}}
"""

            # ------------------------------------------------
            # Groq request
            # ------------------------------------------------

            response = client.chat.completions.create(
                model="qwen/qwen3.6-27b",

                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You are a crime intelligence "
                            "analyst specializing in relationship "
                            "extraction from FIR documents. "
                            "Return ONLY valid JSON."
                        ),
                    },
                    {
                        "role": "user",
                        "content": prompt,
                    },
                ],

                temperature=0,

                # Groq previously rejected ~1055 tokens
                # because the organization's OTPM limit was 1000.
                max_tokens=700,

                response_format={"type": "json_object"},
reasoning_format="hidden",
reasoning_effort="none",
            )

            # ------------------------------------------------
            # Extract model content
            # ------------------------------------------------

            content = (
                response.choices[0]
                .message
                .content
            )

            if not content:

                logger.error(
                    "Groq returned empty content."
                )

                return []

            logger.info(
                "Groq relationship response: "
                f"{content[:1500]}"
            )

            # ------------------------------------------------
            # Parse JSON
            # ------------------------------------------------

            try:

                parsed = json.loads(
                    content
                )

            except json.JSONDecodeError as e:

                logger.error(
                    f"Groq returned invalid JSON: {e}"
                )

                logger.error(
                    f"Raw Groq output: {content[:1500]}"
                )

                return []

            # ------------------------------------------------
            # Validate structure
            # ------------------------------------------------

            try:

                extraction = (
                    LlmExtraction.model_validate(
                        parsed
                    )
                )

            except Exception as e:

                logger.error(
                    f"Groq JSON schema validation failed: {e}"
                )

                logger.error(
                    f"Parsed response: {parsed}"
                )

                return []

            # ------------------------------------------------
            # Convert to application format
            # ------------------------------------------------

            relations = []

            for relation in extraction.relations:

                source = relation.source.strip()
                target = relation.target.strip()

                if not source or not target:
                    continue

                if source.lower() == target.lower():
                    continue

                evidence = (
                    self._find_relationship_evidence(
                        text,
                        source,
                        target,
                    )
                )

                relations.append(
                    {
                        "source": source,
                        "target": target,
                        "relation": relation.relation,
                        "evidence": evidence,
                    }
                )

            logger.info(
                f"Groq extracted {len(relations)} "
                "semantic relationships"
            )

            return relations

        except Exception as e:

            logger.error(
                f"LLM layer error: {e}"
            )

            return []

    # ========================================================
    # RELATIONSHIP EVIDENCE
    # ========================================================

    @staticmethod
    def _find_relationship_evidence(
        text: str,
        source: str,
        target: str,
    ) -> str:

        """
        Find the sentence containing both relationship endpoints.

        This keeps evidence grounded in the original FIR instead
        of asking the LLM to reproduce the sentence.
        """

        if not text:
            return ""

        sentences = re.split(
            r"(?<=[.!?।])\s+|\n+",
            text,
        )

        source_lower = source.lower()
        target_lower = target.lower()

        # ----------------------------------------------------
        # Best case:
        # both entities occur in same sentence
        # ----------------------------------------------------

        for sentence in sentences:

            sentence = sentence.strip()

            if not sentence:
                continue

            sentence_lower = sentence.lower()

            if (
                source_lower in sentence_lower
                and target_lower in sentence_lower
            ):
                return sentence[:500]

        # ----------------------------------------------------
        # Second-best case:
        # source and target occur close together
        # ----------------------------------------------------

        source_position = text.lower().find(
            source_lower
        )

        target_position = text.lower().find(
            target_lower
        )

        if (
            source_position != -1
            and target_position != -1
        ):

            left = max(
                0,
                min(
                    source_position,
                    target_position,
                ) - 150,
            )

            right = min(
                len(text),
                max(
                    source_position + len(source),
                    target_position + len(target),
                ) + 250,
            )

            return text[left:right].strip()[:500]

        return (
            f"Relationship extracted between "
            f"{source} and {target}."
        )

    # ========================================================
    # CO-OCCURRENCE FALLBACK
    # ========================================================

    def _cooccurrence_relations(
        self,
        text: str,
    ) -> list[dict]:

        """
        Fallback relationship extraction.

        IMPORTANT:
        These are NOT semantic relationships.

        They only indicate that two people were mentioned
        in the same paragraph.

        Therefore relation = associate.
        """

        entities_by_para = []

        # ----------------------------------------------------
        # GLiNER
        # ----------------------------------------------------

        if (
            self._extraction_engine == "gliner"
            and self._gliner_model
        ):

            paragraphs = [
                p
                for p in text.split("\n\n")
                if len(p.strip()) > 30
            ]

            for para in paragraphs:

                try:

                    ents = (
                        self._gliner_model
                        .predict_entities(
                            para,
                            ["person"],
                            threshold=GLINER_THRESHOLD,
                        )
                    )

                    persons = list(
                        dict.fromkeys(
                            e["text"].strip()
                            for e in ents
                            if e.get("text", "").strip()
                        )
                    )

                    entities_by_para.append(
                        (
                            para,
                            persons,
                        )
                    )

                except Exception as e:

                    logger.debug(
                        f"GLiNER fallback paragraph failed: {e}"
                    )

        # ----------------------------------------------------
        # spaCy
        # ----------------------------------------------------

        elif (
            self._extraction_engine == "spacy"
            and self._spacy_nlp
        ):

            paragraphs = [
                p
                for p in text.split("\n\n")
                if len(p.strip()) > 30
            ]

            for para in paragraphs:

                try:

                    doc = self._spacy_nlp(
                        para
                    )

                    persons = list(
                        dict.fromkeys(
                            ent.text.strip()
                            for ent in doc.ents
                            if (
                                ent.label_ == "PERSON"
                                and ent.text.strip()
                            )
                        )
                    )

                    entities_by_para.append(
                        (
                            para,
                            persons,
                        )
                    )

                except Exception as e:

                    logger.debug(
                        f"spaCy fallback paragraph failed: {e}"
                    )

        else:
            return []

        # ----------------------------------------------------
        # Build unique relationships
        # ----------------------------------------------------

        relations = []
        seen_pairs = set()

        for para, persons in entities_by_para:

            for i in range(len(persons)):

                for j in range(
                    i + 1,
                    len(persons),
                ):

                    source = persons[i]
                    target = persons[j]

                    pair = tuple(
                        sorted(
                            [
                                source,
                                target,
                            ]
                        )
                    )

                    if pair in seen_pairs:
                        continue

                    seen_pairs.add(pair)

                    relations.append(
                        {
                            "source": pair[0],
                            "target": pair[1],
                            "relation": "associate",
                            "evidence": (
                                "Co-mentioned in paragraph: "
                                f"{para[:300]}..."
                            ),
                        }
                    )

        logger.info(
            f"Co-occurrence fallback generated "
            f"{len(relations)} relationships"
        )

        return relations

    # ========================================================
    # STRUCTURED DATA — CDR
    # ========================================================

    def extract_from_cdr(
        self,
        csv_path: str,
    ) -> list[dict]:

        import pandas as pd

        relations = []

        try:

            df = pd.read_csv(
                csv_path
            )

            for idx, row in df.iterrows():

                from_num = str(
                    row.get(
                        "from_number",
                        row.get(
                            "calling_number",
                            "",
                        ),
                    )
                ).strip()

                to_num = str(
                    row.get(
                        "to_number",
                        row.get(
                            "called_number",
                            "",
                        ),
                    )
                ).strip()

                if not from_num or not to_num:
                    continue

                relations.append(
                    {
                        "source": from_num,
                        "target": to_num,
                        "relation": "phone_call",
                        "evidence": (
                            f"CDR row {idx + 1} @ "
                            f"{row.get('timestamp', 'unknown')} "
                            f"(Duration: "
                            f"{row.get('duration', 'N/A')}s)"
                        ),
                    }
                )

        except Exception as e:

            logger.error(
                f"CDR parsing failed: {e}"
            )

        return relations

